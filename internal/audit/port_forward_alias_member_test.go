// filterModelRuleToGroup is a rule of the firewall filter model to the alias GROUP
// on the web GUI's port, on WAN.
const filterModelRuleToGroup = `<Filter version="1.0.4"><rules>
<rule uuid="c1c1c1c1-0000-4000-8000-000000000001">
<enabled>1</enabled><action>pass</action><interface>wan</interface><direction>in</direction>
<ipprotocol>inet</ipprotocol><protocol>TCP</protocol><source_net>any</source_net>
<destination_net>GROUP</destination_net><destination_port>443</destination_port>
<description>to the forward's target</description>
</rule></rules></Filter>`

// TestRedMode_PortForwardToAliasMember_EndToEnd aims a forward and the rule that
// passes it at an alias holding one of the member forms OPNsense accepts besides
// an address, a CIDR and a range, in each place the rule can be stored.
//
// __lan_network and the like are generated by InterfaceNetworkAliases and never
// written to config.xml, so no alias in the config defines them, and a network
// group naming one holds the LAN network, the firewall's address included. A
// wildcard network matches every address that differs from it only in bits the
// mask sets. Each row but the first of a kind puts the entry that decides second,
// after one that holds nothing.
func TestRedMode_PortForwardToAliasMember_EndToEnd(t *testing.T) {
	t.Parallel()

	const (
		target   = "<target>192.168.10.50</target>"
		address  = "<address>192.168.10.50</address>"
		rulePort = "<port>8443</port>"
		aliases  = "</aliases>"
		stored   = "<rule>\n      <type>pass</type>\n      <associated-rule-id>nat_68dd1c2a4b5c61.23456789"
		firewall = "</Firewall>"
	)

	legacy := readFixture(t, "opnsense-legacy-port-forwards.xml")
	current := readFixture(t, "opnsense-port-forwards.xml")

	requireFixtureHolds(t, legacy, map[string]int{
		target: 1, address: 1, rulePort: 1, aliases: 1, stored: 1, firewall: 1,
	})
	requireFixtureHolds(t, current, map[string]int{target: 1, address: 1, rulePort: 1, aliases: 1})

	// The filter model row keeps only the forward, so the model's rule is the one
	// that decides.
	before, rest, _ := strings.Cut(legacy, stored)
	_, after, _ := strings.Cut(rest, "</rule>")
	withModelRule := strings.Replace(before+after, firewall, filterModelRuleToGroup+firewall, 1)

	stores := []struct {
		name   string
		config string
	}{
		{"legacy store", legacy},
		{"26.1 fixture", current},
		{"filter model", withModelRule},
	}

	tests := []struct {
		name        string
		aliasType   string
		content     string
		wantExposed bool
	}{
		{"an interface network in a network group", "networkgroup", "__lan_network", true},
		{"a second interface network in a network group", "networkgroup", "SPARE_HOST\n__opt1_network", true},
		{"an interface network in a network alias", "network", "192.168.30.0/24\n__wan_network", true},
		{"an interface network in a host alias", "host", "192.168.30.5\n__lan_network", true},
		{"a static table", "networkgroup", "SPARE_HOST\nbogons", true},
		{"a deleted alias", "networkgroup", "SPARE_HOST\nDELETED_ALIAS", true},
		{"a wildcard over the LAN address", "network", "192.168.30.0/24\n192.168.0.1/0.0.255.0", true},
		{"a wildcard of other hosts", "network", "192.168.30.0/24\n192.168.30.1/0.0.0.254", false},
		{"an excluded LAN address", "network", "192.168.30.0/24\n!192.168.10.1", false},
		{"a hostname with a domain", "host", "192.168.30.5\nweb.example.com", false},
		{"country codes", "geoip", "NL\nDE", false},
		{"an alias of another host", "networkgroup", "SPARE_HOST", false},
	}

	for storeIndex, store := range stores {
		for _, tc := range tests {
			t.Run(store.name+", "+tc.name, func(t *testing.T) {
				t.Parallel()

				group := `<alias uuid="d1d1d1d1-0000-4000-8000-00000000000` + strconv.Itoa(storeIndex) + `">` +
					"<name>GROUP</name><type>" + tc.aliasType + "</type>" +
					"<content>" + tc.content + "</content></alias>"

				device := parseConfig(t, strings.NewReplacer(
					target, "<target>GROUP</target>",
					address, "<address>GROUP</address>",
					rulePort, "<port>443</port>",
					aliases, group+aliases,
				).Replace(store.config))

				if got := device.NamedObjects["GROUP"].Members; strings.Join(got, "\n") != tc.content {
					t.Fatalf("GROUP has members %q, want %q", got, tc.content)
				}

				requireRuleToGroup(t, device)
				assertWebGUIExposed(t, device, tc.wantExposed)
			})
		}
	}
}

// requireRuleToGroup fails unless a WAN pass rule names the alias GROUP, so a
// rewrite that stops matching cannot leave a row with no such rule to read.
func requireRuleToGroup(t *testing.T, device *common.CommonDevice) {
	t.Helper()

	for _, rule := range device.FirewallRules {
		if rule.Destination.AddressRef != nil && rule.Destination.AddressRef.Name == "GROUP" &&
			rule.Type == common.RuleTypePass {
			return
		}
	}

	t.Fatal("the rewritten fixture has no pass rule to GROUP")
}
